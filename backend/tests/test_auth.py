SAMPLE_NETSCAPE_TEXT = """# Netscape HTTP Cookie File
# http://curl.haxx.se/rfc/cookie_spec.html
# This file was generated by XakuMedia! Edit at your own risk.

.example.com\tTRUE\t/\tTRUE\t1893456000\tsession_id\tabc123xyz
#HttpOnly_.example.com\tTRUE\t/api\tFALSE\t0\tsecure_token\tsecret999
malformed line with insufficient fields
sub.example.com\tFALSE\t/\tFALSE\t1793456000\tpref_mode\tdark
"""


def test_parse_netscape_cookies() -> None:
    cookies = parse_netscape_cookies(SAMPLE_NETSCAPE_TEXT)
    assert len(cookies) == 3

    # First cookie: .example.com
    c1 = cookies[0]
    assert c1.domain == ".example.com"
    assert c1.flag is True
    assert c1.path == "/"
    assert c1.secure is True
    assert c1.expiration == 1893456000
    assert c1.name == "session_id"
    assert c1.value == "abc123xyz"

    # Second cookie: #HttpOnly_
    c2 = cookies[1]
    assert c2.domain == ".example.com"
    assert c2.path == "/api"
    assert c2.secure is False
    assert c2.expiration == 0
    assert c2.name == "secure_token"
    assert c2.value == "secret999"

    # Third cookie: sub.example.com
    c3 = cookies[2]
    assert c3.domain == "sub.example.com"
    assert c3.flag is False
    assert c3.name == "pref_mode"
    assert c3.value == "dark"


def test_format_netscape_cookies() -> None:
    entries = [
        CookieEntry(
            domain=".artstation.com",
            flag=True,
            path="/",
            secure=True,
            expiration=1893456000,
            name="auth_token",
            value="token_val",
        )
    ]
    formatted = format_netscape_cookies(entries)
    assert "# Netscape HTTP Cookie File" in formatted
    assert ".artstation.com\tTRUE\t/\tTRUE\t1893456000\tauth_token\ttoken_val" in formatted

    # Round trip check
    reparsed = parse_netscape_cookies(formatted)
    assert len(reparsed) == 1
    assert reparsed[0].name == "auth_token"
    assert reparsed[0].value == "token_val"


def test_domain_extraction_and_hierarchy_matching() -> None:
    assert extract_domain_from_url("https://v.redd.it/video123") == "v.redd.it"
    assert extract_domain_from_url("http://example.com:8080/path") == "example.com"
    assert extract_domain_from_url("invalid_url") == "invalid_url"

    headers_map = {
        "redd.it": {"User-Agent": "RedditUA", "Referer": "https://reddit.com"},
        "v.redd.it": {"User-Agent": "VRedditSpecificUA"},
    }

    # Exact match prefers specific subdomain
    exact = match_domain_headers("https://v.redd.it/abc", headers_map)
    assert exact.get("User-Agent") == "VRedditSpecificUA"

    # Parent fallback when child subdomain has no specific entry
    parent = match_domain_headers("https://i.redd.it/img.jpg", headers_map)
    assert parent.get("User-Agent") == "RedditUA"
    assert parent.get("Referer") == "https://reddit.com"

    # Unmatched domain returns empty dict
    unmatched = match_domain_headers("https://example.com", headers_map)
    assert unmatched == {}


def test_build_request_headers_for_url() -> None:
    headers_map = {
        "patreon.com": {
            "Authorization": "Bearer test-patreon-token",
            "Referer": "https://www.patreon.com",
        }
    }
    headers = build_request_headers_for_url("https://www.patreon.com/posts/123", headers_map)

    # Defaults preserved
    assert headers["User-Agent"] == DEFAULT_REQUEST_HEADERS["User-Agent"]
    # Overrides injected
    assert headers["Authorization"] == "Bearer test-patreon-token"
    assert headers["Referer"] == "https://www.patreon.com"


def test_auth_repository_cookie_profiles(repo: MediaRepository) -> None:
    profile_id = str(uuid.uuid4())
    profile = CookieProfileRecord(
        id=profile_id,
        domain="twitter.com",
        browser_source="chrome",
        cookie_file_path="C:/test/twitter_cookies.txt",
        cookie_count=12,
    )
    repo.save_cookie_profile(profile)

    # Retrieve exact
    retrieved = repo.get_cookie_profile(profile_id)
    assert retrieved is not None
    assert retrieved.domain == "twitter.com"
    assert retrieved.cookie_count == 12

    # Subdomain matching (api.twitter.com -> twitter.com)
    sub_retrieved = repo.get_cookie_profile_for_domain("api.twitter.com")
    assert sub_retrieved is not None
    assert sub_retrieved.domain == "twitter.com"

    # List profiles
    profiles = repo.list_cookie_profiles()
    assert len(profiles) == 1
    assert profiles[0].domain == "twitter.com"

    # Delete
    deleted = repo.delete_cookie_profile(profile_id, delete_file=False)
    assert deleted is True
    assert repo.get_cookie_profile(profile_id) is None


def test_auth_repository_domain_headers(repo: MediaRepository) -> None:
    headers = {"User-Agent": "CustomDA/1.0", "Referer": "https://www.deviantart.com"}
    repo.save_domain_headers("deviantart.com", headers)

    # Retrieve
    retrieved = repo.get_domain_headers("deviantart.com")
    assert retrieved is not None
    assert retrieved["User-Agent"] == "CustomDA/1.0"

    # Subdomain lookup (backend.deviantart.com -> deviantart.com)
    sub_retrieved = repo.get_domain_headers("backend.deviantart.com")
    assert sub_retrieved.get("User-Agent") == "CustomDA/1.0"

    # List all
    all_headers = repo.list_all_domain_headers()
    assert "deviantart.com" in all_headers
    assert all_headers["deviantart.com"]["User-Agent"] == "CustomDA/1.0"

    # Delete
    deleted = repo.delete_domain_headers("deviantart.com")
    assert deleted is True
    assert repo.get_domain_headers("deviantart.com") == {}


def test_save_cookies_text_and_import_file(repo: MediaRepository, cookies_dir: Path) -> None:
    profile, entries = save_cookies_text(
        domain="pixiv.net",
        content=SAMPLE_NETSCAPE_TEXT,
        cookies_dir=cookies_dir,
    )
    assert profile.domain == "pixiv.net"
    assert profile.cookie_count == 3
    assert len(entries) == 3
    assert Path(profile.cookie_file_path).exists()

    # Verify get_cookies_dict_from_file loads valid dictionary
    cookies_dict = get_cookies_dict_from_file(profile.cookie_file_path)
    assert cookies_dict["session_id"] == "abc123xyz"
    assert cookies_dict["secure_token"] == "secret999"

    # Test importing from existing file
    import_path = cookies_dir / "external_cookies.txt"
    import_path.write_text(SAMPLE_NETSCAPE_TEXT, encoding="utf-8")

    imported_profile, imported_entries = import_cookies_file(
        file_path=import_path,
        domain_hint="artstation.com",
        cookies_dir=cookies_dir,
    )
    assert imported_profile.domain == "artstation.com"
    assert imported_profile.cookie_count == 3
    assert len(imported_entries) == 3
    assert Path(imported_profile.cookie_file_path).exists()


def test_extract_browser_cookies_mocked(cookies_dir: Path) -> None:
    supported = list_supported_browsers()
    assert "chrome" in supported
    assert "edge" in supported
    assert "firefox" in supported

    # Mock cookie returned by yt-dlp cookie jar
    mock_cookie = MagicMock()
    mock_cookie.domain = ".patreon.com"
    mock_cookie.path = "/"
    mock_cookie.secure = True
    mock_cookie.expires = 1893456000
    mock_cookie.name = "session_token"
    mock_cookie.value = "secret_mock_value"

    with patch("yt_dlp.cookies.extract_cookies_from_browser", return_value=[mock_cookie]):
        profile, entries = extract_browser_cookies(
            browser_name="edge",
            domain_filter="patreon.com",
            cookies_dir=cookies_dir,
        )
        assert profile.domain == "patreon.com"
        assert profile.browser_source == "edge"
        assert profile.cookie_count == 1
        assert len(entries) == 1
        assert entries[0].name == "session_token"
        assert Path(profile.cookie_file_path).exists()

    # Unsupported browser should raise ValueError
    with pytest.raises(ValueError, match="Unsupported browser"):
        extract_browser_cookies(
            browser_name="netscape_navigator_1995",
            domain_filter="patreon.com",
            cookies_dir=cookies_dir,
        )


def test_dispatcher_auth_handlers(repo: MediaRepository) -> None:
    dispatcher = RpcDispatcher(repository=repo)

    # 1. list_supported_browsers
    req = JsonRpcRequest(id="1", method="list_supported_browsers")
    res = dispatcher.dispatch(req)
    assert res.error is None
    assert "browsers" in res.result
    assert "edge" in res.result["browsers"]

    # 2. save_cookies_text
    req = JsonRpcRequest(
        id="2",
        method="save_cookies_text",
        params={"domain": "testsite.com", "content": SAMPLE_NETSCAPE_TEXT},
    )
    res = dispatcher.dispatch(req)
    assert res.error is None
    profile = res.result["profile"]
    assert profile["domain"] == "testsite.com"
    assert profile["cookie_count"] == 3
    profile_id = profile["id"]

    # 3. list_cookie_profiles
    req = JsonRpcRequest(id="3", method="list_cookie_profiles")
    res = dispatcher.dispatch(req)
    assert res.error is None
    assert len(res.result["profiles"]) == 1
    assert res.result["profiles"][0]["domain"] == "testsite.com"

    # 4. set_domain_headers
    req = JsonRpcRequest(
        id="4",
        method="set_domain_headers",
        params={
            "domain": "testsite.com",
            "headers": {"User-Agent": "CustomDispatcherUA/1.0"},
        },
    )
    res = dispatcher.dispatch(req)
    assert res.error is None
    assert res.result["domain"] == "testsite.com"

    # 5. get_domain_headers
    req = JsonRpcRequest(
        id="5",
        method="get_domain_headers",
        params={"domain": "testsite.com"},
    )
    res = dispatcher.dispatch(req)
    assert res.error is None
    assert res.result["headers"]["User-Agent"] == "CustomDispatcherUA/1.0"

    # 6. delete_domain_headers
    req = JsonRpcRequest(
        id="6",
        method="delete_domain_headers",
        params={"domain": "testsite.com"},
    )
    res = dispatcher.dispatch(req)
    assert res.error is None
    assert res.result["deleted"] is True

    # 7. delete_cookie_profile
    req = JsonRpcRequest(
        id="7",
        method="delete_cookie_profile",
        params={"profile_id": profile_id},
    )
    res = dispatcher.dispatch(req)
    assert res.error is None
    assert res.result["deleted"] is True
